export function KvCache() {
  return (
    <Section
      id="kv-cache"
      eyebrow="V · Autoregression"
      title="KV-cache: почему не считаем всё заново"
      number="24"
    >
      <Block kind="intro">
        <p>
          Если бы модель действительно делала <i>полный</i> forward pass на каждом
          шаге генерации, инференс был бы катастрофически медленным. Хорошо то,
          что у меньшей половины операций результат от шага к шагу не меняется —
          это можно <b>кэшировать</b>. Этот трюк называется <b>KV-cache</b>
          (кэш ключей и значений).
        </p>
      </Block>

      <Block kind="formula">
        <p>
          Идея: на шаге t у нас были посчитаны K и V для всех t предыдущих токенов
          в каждом слое. На шаге t+1 нам надо посчитать K и V только для одного
          нового токена — а K и V прежних не меняются (они зависят только от
          residual stream предыдущих позиций, который при causal attention не
          обновляется новым токеном). Поэтому мы их сохраняем в памяти и
          переиспользуем.
        </p>
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`# Без KV-cache: O(n²) на каждом шаге
def autoregress_naive(prompt, max_new=10):
    ids = tokenize(prompt)
    for _ in range(max_new):
        h = E[ids]
        for L in range(36):
            h = transformer_block(h, weights[L])
        next_id = argmax(rms_norm(h, ...) @ E.T)[-1]
        ids.append(next_id)
    # на 100-м токене считаем attention 100×100 каждый шаг

# С KV-cache: O(n) на каждом шаге
def autoregress_cached(prompt, max_new=10):
    ids = tokenize(prompt)
    cache = {L: {"K": [], "V": []} for L in range(36)}

    # шаг 0: полный пасс на промпте, заполняем cache
    h = E[ids]
    for L in range(36):
        h, K_new, V_new = transformer_block_cached(h, weights[L])
        cache[L]["K"], cache[L]["V"] = K_new, V_new

    next_id = argmax(rms_norm(h, ...) @ E.T)[-1]
    ids.append(next_id)

    # шаги 1..max_new: только новый токен через сеть, K/V прежних — из кэша
    for _ in range(max_new - 1):
        h_new = E[[next_id]]                   # один новый токен
        for L in range(36):
            # внутри attention использует cache[L]["K"], cache[L]["V"]
            # для прежних позиций, плюс посчитанные сейчас для нового
            h_new, K_new, V_new = transformer_block_cached(h_new, weights[L], cache[L])
            cache[L]["K"].append(K_new)
            cache[L]["V"].append(V_new)
        next_id = argmax(rms_norm(h_new, ...) @ E.T)[-1]
        ids.append(next_id)`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Почему K и V предыдущих токенов не меняются</h4>
        <p>
          В каждом слое K и V — это функции только от residual stream того же
          токена в начале блока. Causal attention не пускает к токену q информацию
          с позиций k &gt; q. Значит, residual stream позиции q после слоя ℓ зависит
          только от позиций ≤ q — и не зависит от того, что появится в будущем.
          Когда мы добавляем новый токен в конец — все прежние residual stream'ы
          (и их K, V) остаются ровно теми же. Это математическое свойство,
          гарантированное архитектурой.
        </p>
        <h4>Что мы экономим конкретно</h4>
        <p>
          На шаге t у нас в последовательности t + 1 токенов. Без кэша: считаем
          K, V для всех t + 1 (через W_K, W_V — это t + 1 матричных умножений).
          С кэшем: считаем только для одного нового — это 1 матричное умножение.
          Экономия пропорциональна длине последовательности.
        </p>
        <h4>Что мы не можем кэшировать</h4>
        <p>
          Q приходится считать заново на каждом шаге для нового токена — это
          новый запрос, его не было раньше. Но это всего <i>одна</i> позиция, не
          t + 1. Дешёвая операция.
        </p>
        <p>
          Attention scores и softmax — тоже на каждом шаге заново, потому что
          новый токен «спрашивает» у всех t + 1 предыдущих (включая себя), и
          этот запрос новый.
        </p>
        <h4>Какой по размеру KV-cache</h4>
        <p>
          На один токен на один слой: K + V = 2 × (kv_heads × head_dim) = 2 ×
          (2 × 128) = 512 чисел float16 = 1024 байта = 1 КБ. На 36 слоёв = 36 КБ
          на токен. На последовательность из 4096 токенов: 36 × 4096 × 1024 =
          ~144 МБ. Это становится узким местом памяти на длинных контекстах —
          и одна из причин, почему GQA с 2 KV-головами выгоден (без GQA было бы
          16 KV-голов и кэш в 8 раз больше).
        </p>
        <h4>Что происходит на практике</h4>
        <p>
          Все современные LLM-серверы (vllm, llama.cpp, transformers, TGI)
          используют KV-cache по умолчанию. Без него длинные контексты были бы
          недоступны: 8K-, 32K-, 128K-токенные контексты возможны только потому,
          что мы кэшируем K и V и не пересчитываем их.
        </p>
      </Block>

      <Block kind="real">
        <p>
          В нашем семинале с 14 токенами (4 промпт + 10 сгенерированных) экономия
          несущественна, но архитектурно она есть. Если бы мы запускали реальный
          инференс на нашем форвард-пассе, KV-cache бы строился на лету и
          переиспользовался для каждого следующего шага.
        </p>
      </Block>
    </Section>
  );
}
