import { Code, CodeBlock } from '../components/Code';
import { Formula } from '../components/Formula';

export function AttentionV() {
  return (
    <Section
      id="attention-v"
      eyebrow="II · Один transformer-блок"
      title="Считываем V: взвешенная сумма"
      number="12"
    >
      <Block kind="intro">
        <p>
          У нас есть веса внимания (16 матриц 4×4) — это «насколько каждая Q-голова
          и каждая позиция q заинтересована в каждой позиции k». Теперь мы используем
          эти веса, чтобы взять <i>взвешенную сумму</i> V-векторов. Это и есть финальный
          выход attention для одной головы и одной позиции.
        </p>
      </Block>

      <Block kind="formula">
        <Formula tex={`\\text{out}_{h,q} = \\sum_{k=0}^{3} \\mathrm{attn}_{h,q,k} \\cdot V_{k,\\,h//8}`} />
        <p>
          Здесь <Code>out_{`{h,q}`}</Code> — это вектор длины 128 (head_dim) для
          одной Q-головы и одной позиции q. <Code>V_{`{k, h//8}`}</Code> — V-вектор
          для позиции k и соответствующей KV-головы (в GQA одна KV-голова делится
          на 8 Q-голов).
        </p>
        <p>Получившийся тензор out:</p>
        <Formula tex={`\\text{out} \\in \\mathbb{R}^{4 \\times 16 \\times 128}`} />
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`# attn : (16, 4, 4)         — после softmax
# V    : (4, 2, 128)         — value-векторы

out = np.empty((4, 16, 128))
for h in range(16):
    kv_h = h // 8
    for q in range(4):
        out[q, h] = np.zeros(128)
        for k in range(4):
            out[q, h] += attn[h, q, k] * V[k, kv_h]

# то же самое в матричной форме:
# out[q, h] = attn[h, q] @ V[:, h//8, :]`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Как это понять</h4>
        <p>
          Каждый итоговый <Code>out[q, h]</Code> — это смесь V-векторов всех 4 позиций,
          в пропорциях, заданных весами внимания. Если, скажем, на позиции q = 3
          (последний токен « (»), голова h = 5 распределила внимание как
          <Code> attn = [0.1, 0.2, 0.3, 0.4]</Code>, то итоговый out — это
          0.1·V[0] + 0.2·V[1] + 0.3·V[2] + 0.4·V[3].
        </p>
        <h4>Почему именно V</h4>
        <p>
          Помни, что Q, K, V — это разные проекции одного и того же входа.
          Q отвечал «что я ищу», K — «чем я могу быть найден», V — «что я скажу
          если меня выберут». После того как Q × K определило, кто кому интересен,
          мы агрегируем именно V — собственно «содержимое» каждой позиции в нужных
          пропорциях.
        </p>
        <h4>Что было бы, если умножать на K вместо V</h4>
        <p>
          Тогда модель не имела бы свободы развязать «что меня находит» от «что я
          предоставляю». Использование отдельной матрицы V (а не повторного K)
          даёт сети больше выразительной силы: позиция может быть «легко найдена»
          по одному содержимому, но при этом «передавать наружу» нечто другое.
        </p>
        <h4>Что это значит интуитивно</h4>
        <p>
          Каждая Q-голова на позиции q получает «свой персональный коктейль» из
          V-векторов всех 4 позиций. На разных слоях этот коктейль будет разным,
          потому что веса attention — функция от текущего residual stream, который
          меняется со слоями. На раннем слое коктейли почти равномерны (модель
          ещё «не понимает» что происходит); на позднем слое коктейли становятся
          контрастными (одна позиция сильно доминирует).
        </p>
        <h4>Размер промежуточного тензора</h4>
        <p>
          out имеет форму (4, 16, 128) = 8192 чисел. Это для одного слоя и
          одного forward-pass'а. На все 36 слоёв это 295 тысяч чисел в этом
          промежутке (мы их не сохраняем — это служебные значения).
        </p>
      </Block>

      <Block kind="real">
        <p>
          Для нашего forward-pass'а мы сохраняли <i>веса</i> attention (видны в
          предыдущем разделе), но не сохраняли промежуточный out — потому что он
          восстановим из весов и V. В следующем разделе этот out склеивается обратно
          в плоский 2048-вектор и проходит через output-проекцию W_O.
        </p>
      </Block>
    </Section>
  );
}
