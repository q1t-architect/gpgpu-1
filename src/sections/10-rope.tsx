import { Section, Block } from '../components/Section';
import { Code, CodeBlock } from '../components/Code';
import { Formula } from '../components/Formula';
import { RopeClock } from '../widgets/RopeClock';

export function Rope() {
  return (
    <Section
      id="rope"
      eyebrow="II · Один transformer-блок"
      title="RoPE: вращение пар, частоты θ_k"
      number="9"
    >
      <Block kind="intro">
        <p>
          Сейчас будет самая красивая операция в архитектуре. <b>RoPE</b> —{' '}
          Rotary Position Embedding (ро-та-ри по-зи-шн эмбеддинг, «вращательное
          позиционное кодирование»). RoPE кодирует позицию токена через геометрический
          поворот пар координат в head-векторе. Вместо того чтобы прибавлять к
          вектору «позиционный сигнал», RoPE его <i>вращает</i>.
        </p>
        <p>
          Применяется только к Q и K (но не к V) и только внутри attention.
          Это критическая часть, без которой модель не понимала бы порядок токенов.
        </p>
      </Block>

      <Block kind="formula">
        <p>Расшифровка символов:</p>
        <ul>
          <li><span className="glyph"><span className="glyph__symbol">m</span><span className="glyph__name"> (эм)</span></span> — позиция токена в последовательности (у нас 0, 1, 2, 3).</li>
          <li><span className="glyph"><span className="glyph__symbol">k</span><span className="glyph__name"> (ка)</span></span> — индекс пары координат внутри head-вектора, k = 0, 1, …, d_h/2 − 1 (у нас d_h = 128, так что k ∈ 0..63).</li>
          <li><span className="glyph"><span className="glyph__symbol">θ_k</span><span className="glyph__name"> (тета с индексом ка)</span></span> — частота вращения для пары k.</li>
          <li><span className="glyph"><span className="glyph__symbol">α</span><span className="glyph__name"> (альфа)</span></span> — итоговый угол поворота, α = m·θ_k.</li>
          <li><span className="glyph"><span className="glyph__symbol">b</span><span className="glyph__name"> (бэ)</span></span> — база (rope_theta), для классического RoPE = 10000.</li>
        </ul>
        <p>Формула частоты:</p>
        <Formula tex={`\\theta_k = b^{-\\frac{2k}{d_h}}, \\qquad b = 10000, \\quad d_h = 128`} />
        <p>Угол поворота для пары k на позиции m:</p>
        <Formula tex={`\\alpha_{m,k} = m \\cdot \\theta_k`} />
        <p>Поворот пары координат (q_2k, q_2k+1):</p>
        <Formula tex={`\\begin{pmatrix} q'_{2k} \\\\ q'_{2k+1} \\end{pmatrix} = \\begin{pmatrix} \\cos\\alpha & -\\sin\\alpha \\\\ \\sin\\alpha & \\phantom{-}\\cos\\alpha \\end{pmatrix} \\begin{pmatrix} q_{2k} \\\\ q_{2k+1} \\end{pmatrix}`} />
        <p>
          Это стандартная 2D матрица поворота. То же самое делается с K. V
          не вращается.
        </p>
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`def rope(q_or_k, position):
    # q_or_k : shape (head_dim=128,)
    rotated = np.empty_like(q_or_k)
    d = 128
    for k in range(d // 2):                       # 64 пары
        theta_k = 10000 ** (-2 * k / d)
        alpha = position * theta_k
        c, s = np.cos(alpha), np.sin(alpha)
        x = q_or_k[2 * k]
        y = q_or_k[2 * k + 1]
        rotated[2 * k]     = c * x - s * y
        rotated[2 * k + 1] = s * x + c * y
    return rotated

# применяется к каждой Q-голове и каждой K-голове отдельно
for token in range(4):
    for head in range(16):
        Q[token, head] = rope(Q[token, head], position=token)
    for kv_head in range(2):
        K[token, kv_head] = rope(K[token, kv_head], position=token)`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Как читать формулу частоты</h4>
        <p>
          <Code>θ_k = b^(−2k/d_h) = 10000^(−2k/128)</Code>. Подставим крайние k:
        </p>
        <ul>
          <li>k = 0: θ_0 = 10000^0 = <b>1</b> (один радиан на позицию — быстрая стрелка)</li>
          <li>k = 32: θ_32 = 10000^(−0.5) = <b>0.01</b></li>
          <li>k = 63: θ_63 = 10000^(−126/128) ≈ <b>0.0001</b> (медленная стрелка)</li>
        </ul>
        <p>
          То есть пары при малых k крутятся быстро (большой угол на позицию), при
          больших k — почти стоят. Получается набор из 64 «циферблатов с разной
          скоростью» на каждую голову — как геометрическая прогрессия частот в
          часовом механизме.
        </p>
        <h4>Зачем именно вращение</h4>
        <p>
          У вращений есть магическое свойство: <i>скалярное произведение двух
          вращённых векторов зависит только от разницы углов</i>. То есть когда
          модель потом считает Q · K, результат окажется функцией от{' '}
          (m_q − m_k) — относительной разницы позиций между запрашивающим и
          отвечающим токеном. Модель никогда не «видит» абсолютную позицию как
          число, она видит только относительные сдвиги. Это исключительно полезно
          для обобщения на длинные тексты, на которых модель не обучалась.
        </p>
        <h4>Доказательство свойства (на пальцах)</h4>
        <p>
          Если <Code>q' = R(α_q) q</Code> и <Code>k' = R(α_k) k</Code>, то{' '}
          <Code>q' · k' = q^T R(α_q)^T R(α_k) k = q^T R(α_k − α_q) k</Code>.
          Зависит только от разницы α_k − α_q, а α_k − α_q = (m_k − m_q) · θ —
          функция только разности позиций.
        </p>
        <h4>Почему пары координат, а не каждая координата отдельно</h4>
        <p>
          Вращение возможно только в плоскости — нужно как минимум 2 измерения.
          Поэтому мы группируем 128-мерный head-вектор в 64 двумерные «плоскости»,
          каждую из которых вращаем независимо. Это самая компактная схема.
        </p>
        <h4>Почему именно эти частоты</h4>
        <p>
          Геометрическая прогрессия частот (от 1 до ~10⁻⁴) даёт модели
          «многомасштабное» представление позиций: пары с малым k ловят соседние
          различия (соседние токены), пары с большим k — крупномасштабные
          (далёкие токены, абзацы, документы). Это напоминает базис Фурье.
        </p>
        <h4>Что было бы без RoPE</h4>
        <p>
          В классическом Transformer'е использовали <i>absolute positional embeddings</i>:
          к эмбеддингу токена просто прибавляли отдельный «позиционный вектор».
          Это работало, но плохо обобщалось на длины, которых модель не видела.
          RoPE решил эту проблему и стал стандартом для всех современных LLM.
        </p>
        <h4>Почему base = 10000</h4>
        <p>
          Это число из оригинальной статьи RoPE и затем оригинального Transformer'а
          («Attention is all you need», 2017). У некоторых моделей base увеличен
          (например, до 1 000 000) чтобы лучше работать на очень длинных
          контекстах — это растягивает спектр частот и позволяет уникально
          кодировать позиции в десятках тысяч токенов.
        </p>
      </Block>

      <Block kind="demo">
        <RopeClock />
      </Block>

      <Block kind="real">
        <p>
          У нашего Qwen-2.5-3B head_dim = 128, значит на одну голову — 64 пары
          и 64 различных частоты. Голов с такими циферблатами:
        </p>
        <ul>
          <li>16 (Q-голов) × 64 пары × 4 позиции = <b>4096 пар-вращений</b> для Q</li>
          <li>2 (KV-головы) × 64 пары × 4 позиции = <b>512 пар-вращений</b> для K</li>
        </ul>
        <p>
          На <i>каждом из 36 слоёв</i> заново. То есть в одном forward-pass'е
          случается ≈ (4096 + 512) × 36 = 165 888 пар-вращений. Все они полностью
          детерминированы — задаются формулой, а не обучаются. Никакие веса
          модели в RoPE не участвуют.
        </p>
      </Block>
    </Section>
  );
}
