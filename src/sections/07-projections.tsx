import { Section, Block } from '../components/Section';
import { Code, CodeBlock } from '../components/Code';
import { Formula } from '../components/Formula';

export function Projections() {
  return (
    <Section
      id="projections"
      eyebrow="II · Один transformer-блок"
      title="Линейные проекции W_Q, W_K, W_V"
      number="6"
    >
      <Block kind="intro">
        <p>
          Сразу после RMSNorm нормированный вектор каждого токена прогоняется через
          три отдельных матричных умножения — это и есть проекции в Q (query, запрос),
          K (key, ключ) и V (value, значение). Они нужны чтобы attention мог
          определить «кто на кого смотрит и что из этого взять».
        </p>
      </Block>

      <Block kind="formula">
        <p>Обозначения:</p>
        <ul>
          <li><span className="glyph"><span className="glyph__symbol">x</span><span className="glyph__name"> (икс)</span></span> — вход блока после RMSNorm, размер (4, 2048).</li>
          <li><span className="glyph"><span className="glyph__symbol">W_Q</span><span className="glyph__name"> (дабл-ю с индексом Q — матрица проекции в query)</span></span> — обучаемая матрица.</li>
          <li>То же для <Code>W_K</Code> и <Code>W_V</Code>.</li>
        </ul>
        <Formula tex={`Q = x \\cdot W_Q, \\quad K = x \\cdot W_K, \\quad V = x \\cdot W_V`} />
        <p>Размеры (для нашего Qwen-2.5-3B):</p>
        <Formula tex={`W_Q \\in \\mathbb{R}^{2048 \\times 2048}, \\quad W_K, W_V \\in \\mathbb{R}^{2048 \\times 256}`} />
        <Formula tex={`Q \\in \\mathbb{R}^{4 \\times 2048}, \\quad K, V \\in \\mathbb{R}^{4 \\times 256}`} />
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`# x — выход RMSNorm, shape (4, 2048)
W_Q = layer.weights["q_proj"]   # shape (2048, 2048)
W_K = layer.weights["k_proj"]   # shape (2048, 256)
W_V = layer.weights["v_proj"]   # shape (2048, 256)

Q = x @ W_Q                      # (4, 2048)
K = x @ W_K                      # (4, 256)
V = x @ W_V                      # (4, 256)`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Что такое матричное умножение «x · W»</h4>
        <p>
          Каждое из чисел в выходе — это <i>взвешенная сумма</i> всех 2048 чисел
          входа с весами из соответствующего столбца матрицы W. Для одного токена
          и одного выхода <Code>j</Code>:
        </p>
        <Formula tex={`(xW)_j = \\sum_{i=0}^{2047} x_i \\cdot W_{i,j}`} />
        <p>
          То есть <i>все</i> 2048 чисел входа участвуют в производстве <i>каждого</i>{' '}
          из 2048 чисел выхода (для Q). Никто ничего не «выбирает» — всё перемешано
          через обученные веса.
        </p>
        <h4>Почему три отдельных матрицы</h4>
        <p>
          Q, K, V играют принципиально разные роли в attention:
        </p>
        <ul>
          <li><b>Q (query)</b> отвечает на вопрос «что я ищу». Это «запрос» от данного токена ко всем остальным.</li>
          <li><b>K (key)</b> отвечает «чем я могу быть найден». Это «ключ», по которому другие токены могут меня «зацепить».</li>
          <li><b>V (value)</b> отвечает «что я скажу, если меня выберут». Это «содержимое», которое будет передано наружу.</li>
        </ul>
        <p>
          Поскольку роли разные, и матрицы разные. Они обучаются независимо.
          Если бы Q, K, V были одной и той же матрицей, у токена не было бы
          способа отдельно сообщить «то что я ищу» от «то что я предоставляю».
        </p>
        <h4>Почему K и V в Qwen-2.5-3B меньше Q</h4>
        <p>
          У W_Q выход 2048, а у W_K и W_V — всего 256. Это и есть механизм{' '}
          <b>GQA</b>, который разбираем в следующем разделе. Если коротко: модель
          делает 16 разных query-«взглядов», но всего 2 разных key/value-«представления»
          (по 128 чисел каждое: 2 × 128 = 256). Это экономит память и вычисления,
          почти не теряя в качестве.
        </p>
        <h4>Что было бы, если убрать эти проекции</h4>
        <p>
          Если бы Q = K = V = x, то attention превратился бы в «каждый токен
          смотрит на каждый одинаково» — без возможности выделить кому что
          интересно. Проекции дают слою свободу научить разные «спрашивающие»
          и «отвечающие» представления.
        </p>
        <h4>Сколько параметров</h4>
        <p>
          На один слой: W_Q = 2048×2048 = 4.2 М параметров; W_K = W_V = 2048×256 =
          524 K каждая. Итого 4.2 + 0.5 + 0.5 ≈ 5.2 М параметров на слой только
          на Q/K/V; за 36 слоёв это около 187 М. Остальное — это W_O, MLP, и
          embedding-матрица.
        </p>
      </Block>

      <Block kind="real">
        <p>
          В нашем forward-pass'е промежуточные Q, K, V мы не сохраняли (это слишком
          много данных — для каждого слоя по {`4 × 2048 + 2 × (4 × 256) ≈ 10$KB$ × 36`}).
          Но мы знаем что они существуют и какой формы. Размер W_K и W_V выбран
          ровно так, чтобы при reshape в головы получилось 2 KV-головы по 128 чисел —
          об этом следующий раздел.
        </p>
        <p>
          К следующему разделу хорошо запомнить: после этого шага у нас есть
          <Code> Q ∈ ℝ⁴ˣ²⁰⁴⁸</Code>, <Code>K ∈ ℝ⁴ˣ²⁵⁶</Code>, <Code>V ∈ ℝ⁴ˣ²⁵⁶</Code>.
        </p>
      </Block>
    </Section>
  );
}
