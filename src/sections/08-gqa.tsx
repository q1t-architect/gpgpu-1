export function GqaSection() {
  return (
    <Section
      id="gqa"
      eyebrow="II · Один transformer-блок"
      title="GQA: 16 query-голов, 2 KV-головы"
      number="7"
    >
      <Block kind="intro">
        <p>
          Прежде чем перейти к reshape и RoPE — короткое отступление про устройство
          attention в Qwen-2.5-3B. Голов здесь не 16/16, как может показаться по
          умолчанию, а <b>16 на стороне Q и только 2 на стороне K/V</b>. Это
          называется <b>GQA</b> — Grouped Query Attention (груп-к-вэри атеншн,
          «групповое query-внимание»).
        </p>
      </Block>

      <Block kind="formula">
        <p>Параметры архитектуры:</p>
        <CodeBlock lang="pseudo">
{`num_attention_heads = 16    # сколько разных Q-голов
num_key_value_heads = 2     # сколько разных K и V-голов
head_dim            = 128   # длина вектора на одну голову
group_size          = 16 / 2 = 8   # сколько Q-голов делят одну KV-голову`}
        </CodeBlock>
        <p>Соответствие индексов:</p>
        <CodeBlock lang="pseudo">
{`Q-head  0  → KV-head 0       (потому что 0 // 8 = 0)
Q-head  1  → KV-head 0
Q-head  2  → KV-head 0
...
Q-head  7  → KV-head 0
Q-head  8  → KV-head 1       (8 // 8 = 1)
Q-head  9  → KV-head 1
...
Q-head 15  → KV-head 1`}
        </CodeBlock>
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`# После проекций
Q = ...                             # shape (seq=4, hidden=2048)
K = ...                             # shape (seq=4, kv_dim=256)
V = ...                             # shape (seq=4, kv_dim=256)

# Reshape в "головы": last dim делится на (num_heads, head_dim)
Q = Q.reshape(4, 16, 128)           # (seq, q_heads, d_head)
K = K.reshape(4,  2, 128)           # (seq, kv_heads, d_head)
V = V.reshape(4,  2, 128)

# Когда считаем attention для Q-головы h:
def kv_head_for(h):
    return h // (16 // 2)          # = h // 8`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Что такое «многоголовое» внимание</h4>
        <p>
          Идея многоголового attention: вместо одного «взгляда» на токены
          модель делает несколько параллельных «взглядов» — в разных подпространствах
          (разных проекциях). Каждая голова может сфокусироваться на своём типе
          зависимости: одна — на синтаксической связке, другая — на семантической,
          третья — на позициях, и т.д. У классического Transformer'а Q, K, V имели
          одинаковое число голов.
        </p>
        <h4>Зачем тогда уменьшать количество KV-голов</h4>
        <p>
          Эмпирически выяснилось, что <i>разнообразие на стороне Q</i> важнее,
          чем <i>разнообразие на стороне K/V</i>. Грубо говоря: «вопросы» имеют
          больше осмысленных вариаций, чем «ответы». Поэтому можно сильно сжать
          KV-сторону без заметной потери качества. Это даёт два больших выигрыша:
        </p>
        <ul>
          <li>
            <b>Меньше параметров.</b> W_K и W_V становятся в 8 раз компактнее
            (2048×256 вместо 2048×2048), что экономит ~12 М параметров на слой.
          </li>
          <li>
            <b>Меньше памяти на KV-cache.</b> При autoregressive-генерации модель
            хранит K и V всех предыдущих токенов в памяти, чтобы не пересчитывать.
            При GQA этот кэш в 8 раз меньше — критично при длинных контекстах
            (тысячи токенов).
          </li>
        </ul>
        <h4>Спектр вариантов: MHA, GQA, MQA</h4>
        <ul>
          <li>
            <b>MHA</b> — Multi-Head Attention: <Code>num_kv_heads = num_q_heads</Code>.
            Полное разнообразие. Самое тяжёлое.
          </li>
          <li>
            <b>GQA</b> — Grouped Query Attention: <Code>num_kv_heads</Code>{' '}
            делитель <Code>num_q_heads</Code>, но меньше его. Промежуточный
            вариант. Так у Qwen-2.5-3B.
          </li>
          <li>
            <b>MQA</b> — Multi-Query Attention: <Code>num_kv_heads = 1</Code>.
            Все Q-головы делят одну KV-голову. Самый дешёвый, но качество
            заметно падает.
          </li>
        </ul>
        <p>
          GQA — золотая середина, выбранная всеми крупными моделями последних
          поколений: LLaMA-2 70B, Mistral, Qwen-2/2.5, Gemma.
        </p>
        <h4>Что именно делит группа в нашем случае</h4>
        <p>
          У нас 16 Q-голов и 2 KV-головы — значит 8 Q-голов делят одну общую K
          и одну общую V. Каждая из 8 query-голов задаёт свой «вопрос» к одним
          и тем же 4 ключам и значениям. Это словно 8 разных следователей,
          допрашивающих одну и ту же группу свидетелей.
        </p>
        <h4>Что было бы, если бы у нас было MHA</h4>
        <p>
          Тогда W_K, W_V были бы 2048×2048 (а не 2048×256), и K, V после reshape
          стали бы (4, 16, 128). Каждой Q-голове досталась бы своя K и своя V.
          Качество было бы сопоставимое (или чуть лучше), но память и вычисления
          выросли бы в 8 раз.
        </p>
      </Block>

      <Block kind="real">
        <p>
          В Qwen-2.5-3B параметры архитектуры жёстко заданы: <b>num_attention_heads = 16</b>,{' '}
          <b>num_key_value_heads = 2</b>, <b>head_dim = 128</b>. Это значит, что в
          каждом из 36 слоёв 16 query-голов попарно делят 2 K и 2 V. Все 36 слоёв
          устроены одинаково.
        </p>
      </Block>
    </Section>
  );
}
