import { Section, Block } from '../components/Section';
import { Code, CodeBlock } from '../components/Code';
import { Formula } from '../components/Formula';

export function AttentionScores() {
  return (
    <Section
      id="attention-scores"
      eyebrow="II · Один transformer-блок"
      title="Attention: dot product, √d, causal mask"
      number="10"
    >
      <Block kind="intro">
        <p>
          Q и K (после RoPE) — это ключевая пара. Для каждой Q-головы и каждой
          пары токенов q (запрашивающий) и k (отвечающий) мы хотим получить одно
          число — насколько q «заинтересован» в k. Это называется <b>raw attention
          score</b>. Считается через скалярное произведение, нормируется, маскируется
          (от заглядывания в будущее) и потом передаётся в softmax.
        </p>
      </Block>

      <Block kind="formula">
        <p>Скалярное произведение для одной головы и одной пары (q, k):</p>
        <Formula tex={`s_{h,q,k} = \\frac{Q_{q,h} \\cdot K_{k,\\,h//8}}{\\sqrt{d_h}}, \\qquad d_h = 128`} />
        <p>Расшифровка:</p>
        <ul>
          <li><span className="glyph"><span className="glyph__symbol">s</span><span className="glyph__name"> (эс — score, оценка)</span></span> — сырой неотнормированный «уровень внимания».</li>
          <li><span className="glyph"><span className="glyph__symbol">·</span><span className="glyph__name"> (точка — скалярное произведение векторов)</span></span> — это поэлементное умножение и затем сумма: <Code>q · k = Σ q_i k_i</Code>.</li>
          <li><span className="glyph"><span className="glyph__symbol">d_h</span><span className="glyph__name"> (дэ с индексом аш — размер головы)</span></span> = 128.</li>
          <li><span className="glyph"><span className="glyph__symbol">h // 8</span><span className="glyph__name"> (целочисленное деление)</span></span> — выбор KV-головы для текущей Q-головы (GQA).</li>
        </ul>
        <p>Causal mask (каузальная маска): закрываем будущее.</p>
        <Formula tex={`s_{h,q,k} \\leftarrow -\\infty, \\quad \\text{если } k > q`} />
      </Block>

      <Block kind="pseudo">
        <CodeBlock lang="python">
{`import numpy as np

# Q : (4, 16, 128)  — после RoPE
# K : (4,  2, 128)  — после RoPE
d_h = 128
scores = np.empty((16, 4, 4))               # (head, q, k)

for h in range(16):
    kv_h = h // 8
    for q in range(4):
        for k in range(4):
            scores[h, q, k] = np.dot(Q[q, h], K[k, kv_h]) / np.sqrt(d_h)

# Causal mask: q не может смотреть на k > q
mask = np.tril(np.ones((4, 4))) == 0      # верхняя треуг. (без диагонали)
for h in range(16):
    scores[h][mask] = -np.inf`}
        </CodeBlock>
      </Block>

      <Block kind="words">
        <h4>Что такое скалярное произведение и как его читать</h4>
        <p>
          Q-вектор и K-вектор имеют по 128 чисел. Скалярное произведение — это
          сумма произведений по соответствующим позициям: q_0·k_0 + q_1·k_1 + … +
          q_127·k_127. Геометрически: это <i>проекция Q на K</i>, умноженная на
          длину K. Если Q и K «смотрят в одну сторону» — большое положительное
          число. Если перпендикулярны — около нуля. Если в противоположные —
          большое отрицательное.
        </p>
        <h4>Зачем делить на √d_h</h4>
        <p>
          Если Q и K — векторы случайно ориентированных компонент длины d_h, то
          их скалярное произведение в среднем растёт с d_h по дисперсии. Без
          нормировки сырые scores на длинных векторах становятся слишком
          большими, softmax «насыщается» (один элемент даёт ≈ 1, остальные ≈ 0)
          и градиенты во время обучения убивают разнообразие. Деление на √d_h
          компенсирует этот рост и держит scores в осмысленном диапазоне.
          Это <i>scaled dot-product attention</i> — стандартное решение из
          оригинальной статьи 2017 года.
        </p>
        <h4>Что такое causal mask и зачем</h4>
        <p>
          В авторегрессивных языковых моделях токен на позиции q должен
          предсказывать <i>следующий</i> токен, не подсматривая в будущее. Если
          бы мы при обучении позволили токену на позиции q смотреть на токены k &gt; q,
          модель просто скопировала бы будущее и не научилась предсказывать. Поэтому
          мы принудительно ставим −∞ для всех scores с k &gt; q. После softmax эти
          элементы превратятся ровно в 0.
        </p>
        <p>
          Сейчас, на стадии inference (предсказания), causal mask тоже применяется
          — для согласованности и потому что внутри слоёв информация по-прежнему
          должна течь только «слева направо».
        </p>
        <h4>Почему именно −∞</h4>
        <p>
          Softmax — это <Code>e^s_i / Σ e^s_j</Code>. <Code>e^(−∞) = 0</Code> точно.
          Так что замаскированные элементы дают строго нулевую вероятность.
          Если бы мы поставили большое отрицательное число (например, −10⁹),
          результат был бы практически тот же, но по-настоящему «строгого нуля» не
          было бы.
        </p>
        <h4>Получившаяся структура для нашего промпта</h4>
        <p>
          Мы 4 токена и 16 голов. Тензор scores имеет форму (16, 4, 4) — 16
          матриц 4×4. Из-за causal mask каждая такая матрица — нижне-треугольная
          (включая диагональ): только 1+2+3+4 = 10 значимых клеток из 16
          возможных. Остальные 6 клеток = −∞.
        </p>
      </Block>

      <Block kind="real">
        <p>
          В реальном forward-pass'е scores — промежуточная величина, в нашем
          репо мы не сохраняли. Но <b>результат после softmax</b> мы сохраняли —
          и в следующем разделе посмотрим на них напрямую (это файл{' '}
          <Code>attention_weights.bin</Code> формы [36, 16, 4, 4]).
        </p>
      </Block>
    </Section>
  );
}
